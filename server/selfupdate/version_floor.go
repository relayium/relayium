package selfupdate

// minSupportedVersion 是这份二进制**愿意把自己降到的最低版本**。
//
// 为什么需要它：节点本来就拒绝安装比自己旧的版本，但那道防线有两个逃生口——
// 本地 `--force`，以及**中心下发的** AllowDowngrade（更新检查的响应字段）。后者
// 意味着一个被攻破的中心可以把整个车队降到任意一个"签名合法但已知有洞"的旧发布：
// 验签拦不住它，因为那确实是我们自己签过的版本。
//
// 地板是**中心够不着**的那一半：它烧在二进制里，只有能在那台机器上打命令的人
// （`--force`）才能越过。这样正常回滚仍然成立（在地板之上随便回），只有"回到修洞
// 之前"这一种回滚需要人到机器跟前。
//
// 什么时候抬它：**只在一个发布修掉了不能被重新引入的漏洞时**，在同一个 PR 里把它
// 抬到那个发布的版本号。平时的发布**不要**动它——抬得太勤等于把正常回滚的窗口
// 一起关掉，那比它挡住的风险更常发生。
//
// 空字符串表示"未设置地板"（开发构建、以及这个机制上线之前的构建），此时行为与
// 改动前完全一致。TestVersionFloor 钉住这些语义。
//
// 是 var 不是 const，只为了测试能替换；生产里只在这里改一次。
var minSupportedVersion = ""
