// عدد + معدود. Arabic has no single form the way English's "file(s)" has one:
// the counted noun changes shape with the number, so a `${n} ملف` template is
// wrong for every n but 1 — it renders "3 يوم" and "14 يوم" where the hardcoded
// siblings in this very file already say "3 أيام" and "14 يومًا".
//
// The five buckets below are the classical rule, which is also what CLDR calls
// one/two/few/many/other for `ar`:
//   1        singular, no digit           ملف واحد
//   2        dual, no digit               ملفان
//   3–10     genitive plural              3 ملفات
//   11–99    accusative singular + tanwīn 14 ملفًا
//   0, 100+  bare singular                100 ملف
// Only the dual is visibly case-marked in undiacritised text, so a noun that
// lands in an accusative or genitive slot needs its own record (…Obl) and the
// other four forms can be shared.
interface Counted {
  one: string;
  two: string;
  few: string;
  many: string;
  other: string;
}

const count = (n: number, w: Counted): string => {
  const r = n % 100;
  if (n === 1) return w.one;
  if (n === 2) return w.two;
  if (r >= 3 && r <= 10) return `${n} ${w.few}`;
  if (r >= 11) return `${n} ${w.many}`;
  return `${n} ${w.other}`;
};

