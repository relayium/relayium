// Building the REAL server for a fixture, on a platform it was never ported to.
//
// ## The blocker this exists for
//
// `server/internal/storage/usage.go` calls `syscall.Statfs`, which does not
// exist on Windows. Its own header says so: "available on Unix (darwin +
// linux), which matches the deployment target; a //go:build unix guard plus a
// Windows fallback can be added if a Windows build is ever needed." So the
// Windows lane's Device Inbox acceptance failed at SETUP — before any of its 39
// checks ran — because the server would not compile, not because anything it
// asserts regressed.
//
// ## What this does, precisely
//
// A Go `-overlay` that replaces EXACTLY ONE FILE, `internal/storage/usage.go`,
// for Windows builds only. Every other file of the server — every HTTP handler,
// every route, the protocol, the database, auth — is the unmodified product
// source. The overlay file is generated into the TASK ROOT, never into the
// repository, and its provenance is returned to the caller so a run can say what
// it built.
//
// ## What the replacement is, and what it is NOT
//
// It is a real Win32 capacity probe: `GetDiskFreeSpaceExW`, through the
// `golang.org/x/sys/windows` binding the server module already requires
// (`server/go.mod:17`). No fake constant, no stub, no quota invention; errors
// propagate exactly as the Unix implementation's do, and the totals stay
// `uint64`.
//
// It is NOT a Windows port of the server, and this fixture makes no
// quota-parity claim. Microsoft documents `GetDiskFreeSpaceExW`'s
// `lpFreeBytesAvailableToCaller` and `lpTotalNumberOfBytes` as values available
// TO THE CALLING USER — under a per-user disk quota they are the caller's quota,
// not the volume's global capacity. The Unix implementation reports
// `st.Blocks * bsize`, i.e. ALL blocks. The two are the same number only where
// no quota applies. So what a Windows fixture run measures is a
// quota-aware OS probe of the same shape, and nothing here may be read as
// "Windows and Unix report identical capacity" or as authority to ship the
// server on Windows.
//
// ## The guard, which is the point
//
// The original file is hash- and shape-checked before any overlay is written. If
// production changes `usage.go`, this REFUSES rather than silently overlaying a
// stale replacement — the failure mode that would otherwise hide a real change
// behind a fixture. Updating the constant below is a deliberate act with a diff.
import { spawn } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { createHash } from "node:crypto";

/**
 * `server/internal/storage/usage.go` as reviewed, in BOTH line-ending forms.
 *
 * The Windows lane checked the file out with CRLF endings, so a byte hash of the
 * reviewed content did not match and the guard correctly refused — the first
 * Windows run never reached the probe. That is newline conversion by the
 * checkout, not a change to the server source: the CRLF digest below is exactly
 * `sha256(reviewedLF.replaceAll("\n", "\r\n"))`, verified on both sides.
 *
 * Two EXACT digests, deliberately, rather than normalising before hashing.
 * Accepting "the reviewed bytes, or the reviewed bytes with LF->CRLF applied"
 * still refuses everything else — a changed body, a stray bare CR, a trimmed
 * trailing newline — whereas a whitespace-normalising guard would wave those
 * through. The guard's whole job is to refuse a production change it cannot see.
 */
export const ORIGINAL_USAGE_SHA256 =
  "fddcb1225dd71d369a48fc9fcf0009003ba63683a35b9b3f7dbeb3f975b7c8a4";
/** The same reviewed content, LF->CRLF, as a Windows checkout produces it. */
export const ORIGINAL_USAGE_SHA256_CRLF =
  "ae2932d5caa6c81064c509bc5f17306e707cd8acaa6e9b03f64769b06933ee25";

/** The signature the replacement must keep answering. */
const REQUIRED_SIGNATURE = "func DiskUsage(path string) (used, total uint64, err error)";

const RELATIVE_TARGET = "internal/storage/usage.go";

/**
 * The Windows replacement.
 *
 * `used = total - min(availableToCaller, total)` mirrors the Unix arithmetic,
 * including its clamp: a caller whose available bytes exceed the reported total
 * (which a quota can produce) must not underflow a `uint64`.
 */
const WINDOWS_USAGE_GO = `package storage

// FIXTURE-ONLY. Generated by apps/windows/test/smoke/server-platform.mjs.
//
// Overlays the reviewed server/internal/storage/usage.go for a WINDOWS TEST
// build. Not a Windows port of Relayium's server and not part of any shipped
// artifact: it exists so a Windows CI runner can build and run the REAL HTTP
// handlers, which is what the acceptance fixtures actually assert.
//
// GetDiskFreeSpaceExW reports what is available TO THE CALLING USER. Under a
// per-user disk quota that is the caller's quota rather than the volume's global
// capacity, so this is a quota-aware probe of the same SHAPE as the Unix
// statfs implementation, not a proven-identical measurement of it.

import "golang.org/x/sys/windows"

// DiskUsage reports used and total bytes for the volume backing path, via
// GetDiskFreeSpaceExW. Errors propagate unchanged.
func DiskUsage(path string) (used, total uint64, err error) {
	p, err := windows.UTF16PtrFromString(path)
	if err != nil {
		return 0, 0, err
	}
	var availableToCaller, totalBytes, totalFree uint64
	if err := windows.GetDiskFreeSpaceEx(p, &availableToCaller, &totalBytes, &totalFree); err != nil {
		return 0, 0, err
	}
	avail := availableToCaller
	if avail > totalBytes {
		avail = totalBytes
	}
	return totalBytes - avail, totalBytes, nil
}
`;

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

/**
 * Decide, and materialise, what this build needs.
 *
 * Returns `{ args, provenance }`. `args` is empty on every non-Windows target —
 * there is no overlay at all there, and the product file is compiled as written.
 */
export async function prepareServerOverlay({ repoRoot, taskRoot, goos = process.platform }) {
  const windowsTarget = goos === "win32" || goos === "windows";
  const targetPath = join(repoRoot, "server", RELATIVE_TARGET);
  // Raw bytes: the line-ending form is exactly what is being judged here, so it
  // must not be lost to a decode.
  const rawBytes = await readFile(targetPath);
  const digest = sha256(rawBytes);
  const original = rawBytes.toString("utf8");
  const form = digest === ORIGINAL_USAGE_SHA256 ? "lf"
    : digest === ORIGINAL_USAGE_SHA256_CRLF ? "crlf" : null;

  // Checked on EVERY platform, including the ones that need no overlay: a
  // production change to this file must be noticed where it happens, not only
  // on the runner that would have overlaid it.
  if (form === null) {
    throw new Error(
      `SETUP: ${RELATIVE_TARGET} is not the reviewed file (sha256 ${digest}; expected ` +
      `${ORIGINAL_USAGE_SHA256} as checked out with LF, or ${ORIGINAL_USAGE_SHA256_CRLF} with CRLF). ` +
      `The fixture overlay refuses to hide a production change: review the new implementation and ` +
      `update the constants deliberately.`);
  }
  if (!original.includes(REQUIRED_SIGNATURE)) {
    throw new Error(`SETUP: ${RELATIVE_TARGET} no longer declares \`${REQUIRED_SIGNATURE}\``);
  }

  if (!windowsTarget) {
    return { args: [], provenance: { overlaid: false, target: goos, original: digest, form } };
  }

  const dir = join(taskRoot, "server-overlay");
  await mkdir(dir, { recursive: true });
  const replacement = join(dir, "usage_windows_fixture.go");
  await writeFile(replacement, WINDOWS_USAGE_GO, "utf8");
  const overlayJSON = join(dir, "overlay.json");
  await writeFile(overlayJSON, JSON.stringify({ Replace: { [targetPath]: replacement } }, null, 2), "utf8");

  return {
    args: ["-overlay", overlayJSON],
    provenance: {
      overlaid: true,
      target: "windows",
      replaced: RELATIVE_TARGET,
      original: digest,
      form,
      replacement: sha256(Buffer.from(WINDOWS_USAGE_GO, "utf8")),
      overlayJSON,
      note: "real Go HTTP handlers, unmodified, plus a test-only Windows disk-probe adapter; "
        + "not an unmodified whole binary and not a Windows server port",
    },
  };
}

const GO = process.platform === "win32" ? "go.exe" : "go";
const CLOSE_BUDGET_MS = 4_000;

/**
 * A result that may be called success.
 *
 * Exit 0 alone is not it. A child the BUDGET terminated can still report 0, a
 * child that never spawned reports nothing at all, and a child that was never
 * observed closed is not a finished child. Each of those read as success once.
 */
const healthy = (r) => r.code === 0 && !r.timedOut && !r.unjoined && !r.spawnError;

/**
 * Run one `go` command as a child this module OWNS and JOINS.
 *
 * ## Why this is not a plain `spawn` + `await close`
 *
 * A build or a test compile is still a child process, and this fixture's whole
 * contract is that every child is ledgered before the first await, terminated by
 * its own handle, and OBSERVED closed. An earlier version of this function broke
 * that three ways, and each one is fixed here rather than argued about:
 *
 *   1. its `error` handler resolved the promise, so a run could report a result
 *      BEFORE the child was observed closed — the exact "claimed clean on
 *      something other than a close" failure this fixture exists to refuse;
 *   2. its timeout sent SIGKILL and then waited forever, so a child that did not
 *      die produced a hang instead of a reported finding;
 *   3. it was invisible to the caller's registry, so the orchestrator could
 *      neither list it nor join it.
 *
 * `register` is how the caller takes ownership: it is handed the live child and
 * a label AT SPAWN, before anything is awaited, so the orchestrator's own
 * `stopChildren` can reach it. The ledger is returned either way.
 *
 * `unjoined: true` means the child was NOT observed closed. The caller must
 * treat that as a cleanup finding, retain its task root, and fail — never
 * remove a directory a live process may still hold.
 */
function runOwned(file, args, { cwd, env, timeoutMs, label, register }) {
  return new Promise((resolve) => {
    const child = spawn(file, args, { cwd, env, stdio: ["ignore", "pipe", "pipe"] });
    // Subscribed AT SPAWN, so a fast exit is not raced.
    let closed = false;
    let exitCode = null;
    let exitSignal = null;
    let spawnError = null;
    // Set when the budget fires, so a child the BUDGET killed is never reported
    // as having finished on its own: the close that follows a forced
    // termination looks identical to a natural one.
    let budgetFired = false;
    const onClose = new Promise((res) => {
      child.once("close", (code, signal) => {
        closed = true;
        exitCode = code;
        exitSignal = signal;
        res();
      });
      child.once("error", (err) => {
        // A child that never spawned emits no `close`; anything else must still
        // wait for one. Resolving here in the general case is what let a result
        // be reported before the process was observed gone.
        spawnError = String(err?.message ?? err);
        if (child.pid === undefined) { closed = true; res(); }
      });
    });
    const ledger = { pid: child.pid ?? null, ppid: process.pid, label, argv: [file, ...args], cwd };
    register?.(child, label, ledger);

    let out = "";
    let err = "";
    child.stdout.on("data", (d) => { out = (out + d).slice(-16000); });
    child.stderr.on("data", (d) => { err = (err + d).slice(-16000); });

    const settle = (timedOut, unjoined) => resolve({
      code: exitCode, signal: exitSignal, timedOut, unjoined, closed, ledger,
      spawnError, stdout: out.slice(-8000), stderr: err.slice(-8000), argv: ledger.argv,
    });

    const wait = (ms) => Promise.race([onClose.then(() => true), new Promise((r) => setTimeout(() => r(false), ms))]);

    const budget = setTimeout(async () => {
      budgetFired = true;
      // SIGTERM, bounded wait, SIGKILL, bounded wait — by this child's own
      // handle. On Windows both are `TerminateProcess`; the observed close is
      // what is reported either way.
      try { child.kill("SIGTERM"); } catch { /* already gone */ }
      if (await wait(CLOSE_BUDGET_MS)) return settle(true, false);
      try { child.kill("SIGKILL"); } catch { /* already gone */ }
      if (await wait(CLOSE_BUDGET_MS)) return settle(true, false);
      child.unref?.();
      settle(true, true);
    }, timeoutMs);

    void onClose.then(() => { clearTimeout(budget); settle(budgetFired, false); });
  });
}

/**
 * The shared build primitive: Inbox, realtime and any later fixture use this one
 * so the overlay decision cannot drift between them.
 *
 * `register` is forwarded so the build's child belongs to the caller's registry.
 */
export async function buildServerForFixture({
  repoRoot, taskRoot, outPath, goos = process.platform, goarch = null,
  timeoutMs = 8 * 60 * 1000, env = process.env, register = null,
}) {
  const { args, provenance } = await prepareServerOverlay({ repoRoot, taskRoot, goos });
  const childEnv = { ...env };
  if (goos === "windows" && process.platform !== "win32") childEnv.GOOS = "windows";
  if (goarch) childEnv.GOARCH = goarch;
  const result = await runOwned(GO, ["build", ...args, "-o", outPath, "."], {
    cwd: join(repoRoot, "server"), env: childEnv, timeoutMs, label: "go-build[server]", register,
  });
  return { ...result, provenance, ok: healthy(result) };
}

/**
 * The Windows positive control: the package's own `TestDiskUsage`, compiled
 * against the replacement and RUN AS AN OWNED CHILD.
 *
 * Two steps on purpose. `go test` compiles a test binary and then runs it as a
 * child of its own, so killing `go` can leave that executable behind — a
 * grandchild outside every ledger, which is precisely what this fixture may not
 * have. `go test -c` only compiles; the binary is then executed here, ledgered
 * and joined like any other child.
 *
 * Runs only where the overlay applies. On a host that is not Windows the product
 * file is what the package's own tests already cover.
 */
export async function testDiskUsageWithOverlay({
  repoRoot, taskRoot, timeoutMs = 5 * 60 * 1000, env = process.env, register = null,
}) {
  const { args, provenance } = await prepareServerOverlay({ repoRoot, taskRoot, goos: process.platform });
  if (!provenance.overlaid) {
    return { skipped: true, why: `no overlay on ${process.platform}; the product file is what runs here`, provenance };
  }
  const probe = join(taskRoot, "server-overlay", process.platform === "win32" ? "diskusage.test.exe" : "diskusage.test");
  const compiled = await runOwned(GO, ["test", ...args, "-c", "-o", probe, "./internal/storage"], {
    cwd: join(repoRoot, "server"), env, timeoutMs, label: "go-test-compile[storage]", register,
  });
  // A budget-terminated compile can still exit 0 on some platforms; treated as
  // success it would run a stale or absent probe binary and call it a pass.
  if (!healthy(compiled)) {
    return { ...compiled, provenance, ok: false, skipped: false, stage: "compile" };
  }
  const ran = await runOwned(probe, ["-test.run", "TestDiskUsage", "-test.v", "-test.count=1"], {
    cwd: join(repoRoot, "server"), env, timeoutMs, label: "diskusage-probe", register,
  });
  return { ...ran, provenance, ok: healthy(ran), skipped: false, stage: "run", compile: compiled.ledger };
}
